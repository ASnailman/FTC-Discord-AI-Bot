"""Turn before/after eval JSON pairs into a markdown delta table.

    python scripts/compare_evals.py \\
        evals/before_extraction.json evals/after_extraction.json \\
        evals/before_retrieval.json evals/after_retrieval.json \\
        evals/before_answers.json evals/after_answers.json \\
        --markdown docs/evaluation-results.md
"""
import argparse
import json
from pathlib import Path

# (json key, display label, higher-is-better, is-percentage)
METRICS = {
    "extraction": [
        ("micro_precision", "Extraction micro-precision", True, False),
        ("micro_recall", "Extraction micro-recall", True, False),
        ("exact_match_rate", "Extraction exact-match rate", True, False),
    ],
    "retrieval": [
        ("team_precision_at_k", "Team precision@k", True, False),
        ("season_precision_at_k", "Season precision@k", True, False),
        ("context_purity_at_k", "Context purity@k", True, False),
        ("avg_foreign_teams_in_context", "Avg. foreign teams in context", False, False),
        ("avg_wasted_context_chars", "Avg. wasted context chars", False, False),
    ],
    "answers": [
        ("required_facts_present_rate", "Required facts present", True, False),
        ("forbidden_facts_absent_rate", "Forbidden facts absent", True, False),
        ("truncation_rate", "Truncation rate", False, False),
        ("answer_stability", "Answer stability (repeat runs agree)", True, False),
    ],
}


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def find_kind(data):
    for kind, metrics in METRICS.items():
        if any(key in data for key, *_ in metrics):
            return kind
    return None


def render_section(kind, before, after):
    lines = [f"## {kind.capitalize()}", "", "| Metric | Before | After | Change | Target met |", "|---|---|---|---|---|"]
    for key, label, higher_better, _ in METRICS[kind]:
        b = before.get(key)
        a = after.get(key)
        if b is None or a is None:
            continue
        delta = a - b
        arrow = "+" if delta >= 0 else ""
        improved = (delta >= 0) if higher_better else (delta <= 0)
        mark = "yes" if improved else "no"
        lines.append(f"| {label} | {b} | {a} | {arrow}{round(delta, 3)} | {mark} |")
    lines.append("")
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("files", nargs="+", help="alternating before/after JSON report paths")
    p.add_argument("--markdown", required=True, help="output markdown path")
    args = p.parse_args()

    if len(args.files) % 2 != 0:
        raise SystemExit("expected an even number of files (before, after, before, after, ...)")

    sections = []
    for i in range(0, len(args.files), 2):
        before = load(args.files[i])
        after = load(args.files[i + 1])
        kind = find_kind(before) or find_kind(after)
        if not kind:
            print(f"skipping unrecognized report pair: {args.files[i]}, {args.files[i+1]}")
            continue
        sections.append(render_section(kind, before, after))

    header = (
        "# Evaluation Results\n\n"
        "Generated by `scripts/compare_evals.py`. Reproduce with:\n\n"
        "```\n"
        "python scripts/eval_extraction.py --mode before --report evals/before_extraction.json\n"
        "python scripts/eval_extraction.py --mode after  --report evals/after_extraction.json\n"
        "python scripts/eval_retrieval.py  --mode before --report evals/before_retrieval.json\n"
        "python scripts/eval_retrieval.py  --mode after  --report evals/after_retrieval.json\n"
        "python scripts/eval_answers.py    --mode before --runs 2 --report evals/before_answers.json\n"
        "python scripts/eval_answers.py    --mode after  --runs 2 --report evals/after_answers.json\n"
        "python scripts/compare_evals.py evals/before_extraction.json evals/after_extraction.json "
        "evals/before_retrieval.json evals/after_retrieval.json "
        "evals/before_answers.json evals/after_answers.json --markdown docs/evaluation-results.md\n"
        "```\n\n"
        "\"Before\" reproduces the original algorithm/retrieval path exactly "
        "(see `scripts/_original_extract_info.py` and `ask_bot(team_nums=None)`); "
        "it is not a guess.\n\n"
    )

    Path(args.markdown).parent.mkdir(parents=True, exist_ok=True)
    with open(args.markdown, "w", encoding="utf-8") as f:
        f.write(header + "\n".join(sections))

    print(f"Wrote {args.markdown}")


if __name__ == "__main__":
    main()
